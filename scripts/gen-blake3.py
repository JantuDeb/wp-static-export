#!/usr/bin/env python3
"""Generates src/engine/blake3.php: BLAKE3 (default hash mode, 32-byte output) in pure PHP with the
compression function fully unrolled. PHP function calls are slow, so the 56 G calls are inlined."""
import sys

MSG_PERM = [2, 6, 3, 10, 7, 0, 4, 13, 1, 11, 12, 5, 9, 14, 15, 8]
IV = [0x6A09E667, 0xBB67AE85, 0x3C6EF372, 0xA54FF53A, 0x510E527F, 0x9B05688C, 0x1F83D9AB, 0x5BE0CD19]

def g(a, b, c, d, mx, my):
    # All values are kept as 32-bit unsigned ints in 64-bit PHP integers.
    return f"""
        ${a} = (${a} + ${b} + {mx}) & 0xFFFFFFFF; $t = ${d} ^ ${a}; ${d} = (($t >> 16) | ($t << 16)) & 0xFFFFFFFF;
        ${c} = (${c} + ${d}) & 0xFFFFFFFF; $t = ${b} ^ ${c}; ${b} = (($t >> 12) | ($t << 20)) & 0xFFFFFFFF;
        ${a} = (${a} + ${b} + {my}) & 0xFFFFFFFF; $t = ${d} ^ ${a}; ${d} = (($t >> 8) | ($t << 24)) & 0xFFFFFFFF;
        ${c} = (${c} + ${d}) & 0xFFFFFFFF; $t = ${b} ^ ${c}; ${b} = (($t >> 7) | ($t << 25)) & 0xFFFFFFFF;"""

def round_code(m):
    out = []
    out.append(g('v0', 'v4', 'v8', 'v12', m[0], m[1]))
    out.append(g('v1', 'v5', 'v9', 'v13', m[2], m[3]))
    out.append(g('v2', 'v6', 'v10', 'v14', m[4], m[5]))
    out.append(g('v3', 'v7', 'v11', 'v15', m[6], m[7]))
    out.append(g('v0', 'v5', 'v10', 'v15', m[8], m[9]))
    out.append(g('v1', 'v6', 'v11', 'v12', m[10], m[11]))
    out.append(g('v2', 'v7', 'v8', 'v13', m[12], m[13]))
    out.append(g('v3', 'v4', 'v9', 'v14', m[14], m[15]))
    return ''.join(out)

m = [f'$m{i}' for i in range(16)]
rounds = []
cur = m[:]
for r in range(7):
    rounds.append(round_code(cur))
    cur = [cur[i] for i in MSG_PERM]

compress_body = ''.join(rounds)
iv = ', '.join(hex(x) for x in IV)

tmpl = r'''<?php
// GENERATED by scripts/gen-blake3.py: do not edit by hand.

namespace WP_Static_Export\Engine;

// Exit if accessed directly.
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * BLAKE3 (default hash mode, 32 byte output) in pure PHP.
 *
 * Needed because Cloudflare identifies uploaded assets by a BLAKE3 hash and PHP has no native implementation.
 * Requires 64-bit integers.
 */
class Blake3 {

	const CHUNK_START = 1;
	const CHUNK_END   = 2;
	const PARENT      = 4;
	const ROOT        = 8;

	const IV = array( @@IV@@ );

	/**
	 * @param string $data Bytes.
	 * @return string 64 hex characters.
	 */
	public static function hash_hex( $data ) {
		return bin2hex( self::hash( $data ) );
	}

	/**
	 * @param string $data Bytes.
	 * @return string 32 raw bytes.
	 */
	public static function hash( $data ) {
		$len   = strlen( $data );
		$stack = array();
		$count = 0;
		$pos   = 0;

		// Every chunk but the last becomes a chaining value merged into a stack of subtree roots.
		while ( $len - $pos > 1024 ) {
			$out = self::chunk_state( substr( $data, $pos, 1024 ), $count );
			$cv  = array_slice( self::compress( $out[0], $out[1], $count, $out[2], $out[3] ), 0, 8 );
			$pos += 1024;
			++$count;
			for ( $total = $count; 0 === ( $total & 1 ); $total >>= 1 ) {
				$cv = array_slice( self::compress( self::IV, array_merge( array_pop( $stack ), $cv ), 0, 64, self::PARENT ), 0, 8 );
			}
			$stack[] = $cv;
		}

		$out = self::chunk_state( substr( $data, $pos ), $count );
		if ( ! $stack ) {
			return self::to_bytes( self::compress( $out[0], $out[1], $count, $out[2], $out[3] | self::ROOT ) );
		}
		$cv = array_slice( self::compress( $out[0], $out[1], $count, $out[2], $out[3] ), 0, 8 );
		while ( $stack ) {
			$flags = self::PARENT | ( 1 === count( $stack ) ? self::ROOT : 0 );
			$words = self::compress( self::IV, array_merge( array_pop( $stack ), $cv ), 0, 64, $flags );
			$cv    = array_slice( $words, 0, 8 );
		}

		return self::to_bytes( $words );
	}

	/**
	 * Run every block of a chunk except the last; return the inputs of the last compression.
	 *
	 * @param string $bytes Chunk bytes (0..1024).
	 * @param int    $index Chunk counter.
	 * @return array [ chaining value, message words, block length, flags ]
	 */
	protected static function chunk_state( $bytes, $index ) {
		$cv     = self::IV;
		$len    = strlen( $bytes );
		$blocks = max( 1, (int) ceil( $len / 64 ) );
		$flags  = self::CHUNK_START;
		for ( $b = 0; $b < $blocks - 1; $b++ ) {
			$words = array_values( unpack( 'V16', substr( $bytes, $b * 64, 64 ) ) );
			$cv    = array_slice( self::compress( $cv, $words, $index, 64, $flags ), 0, 8 );
			$flags = 0;
		}
		$tail  = substr( $bytes, ( $blocks - 1 ) * 64 );
		$words = array_values( unpack( 'V16', str_pad( $tail, 64, "\0" ) ) );

		return array( $cv, $words, strlen( $tail ), $flags | self::CHUNK_END );
	}

	/**
	 * @param int[] $words At least 8 words.
	 * @return string 32 bytes.
	 */
	protected static function to_bytes( $words ) {
		return pack( 'V8', ...array_slice( $words, 0, 8 ) );
	}

	/**
	 * The BLAKE3 compression function.
	 *
	 * @param int[] $cv      8 chaining words.
	 * @param int[] $block   16 message words.
	 * @param int   $counter Block counter.
	 * @param int   $len     Block length in bytes.
	 * @param int   $flags   Domain flags.
	 * @return int[] 16 words.
	 */
	protected static function compress( $cv, $block, $counter, $len, $flags ) {
		list( $m0, $m1, $m2, $m3, $m4, $m5, $m6, $m7, $m8, $m9, $m10, $m11, $m12, $m13, $m14, $m15 ) = $block;
		list( $v0, $v1, $v2, $v3, $v4, $v5, $v6, $v7 ) = $cv;
		$v8  = 0x6A09E667;
		$v9  = 0xBB67AE85;
		$v10 = 0x3C6EF372;
		$v11 = 0xA54FF53A;
		$v12 = $counter & 0xFFFFFFFF;
		$v13 = ( $counter >> 32 ) & 0xFFFFFFFF;
		$v14 = $len;
		$v15 = $flags;
@@BODY@@
		return array(
			$v0 ^ $v8, $v1 ^ $v9, $v2 ^ $v10, $v3 ^ $v11, $v4 ^ $v12, $v5 ^ $v13, $v6 ^ $v14, $v7 ^ $v15,
			$v8 ^ $cv[0], $v9 ^ $cv[1], $v10 ^ $cv[2], $v11 ^ $cv[3], $v12 ^ $cv[4], $v13 ^ $cv[5], $v14 ^ $cv[6], $v15 ^ $cv[7],
		);
	}
}
'''
php = tmpl.replace('@@IV@@', iv).replace('@@BODY@@', compress_body)
open('src/engine/blake3.php', 'w').write(php)
print('written', len(php))
